#!/usr/bin/env bash
# Assemble a static site for GitHub Pages from static/.
# Env:
#   API_BASE_URL           public HTTPS origin of the Rust API (required for Pages try-it + Shortcut)
#   SHORTCUT_INSTALL_URL   optional iCloud Shortcut link
#   PAGES_BASE_PATH        default /uni-share for project Pages; use / for a custom domain at root
#   OUT_DIR                default _site
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT_DIR="${OUT_DIR:-$ROOT/_site}"
API_BASE_URL="${API_BASE_URL:-}"
SHORTCUT_INSTALL_URL="${SHORTCUT_INSTALL_URL:-}"
PAGES_BASE_PATH="${PAGES_BASE_PATH:-/uni-share}"

# Normalize base path: leading slash, trailing slash (except bare "/")
if [[ "$PAGES_BASE_PATH" != "/" ]]; then
  PAGES_BASE_PATH="/${PAGES_BASE_PATH#/}"
  PAGES_BASE_PATH="${PAGES_BASE_PATH%/}/"
fi

API_BASE_URL="${API_BASE_URL%/}"

rm -rf "$OUT_DIR"
mkdir -p "$OUT_DIR"
cp -R "$ROOT/static/." "$OUT_DIR/"

# Point <base href> at the Pages project path so relative asset links resolve.
find "$OUT_DIR" -name '*.html' -print0 | while IFS= read -r -d '' file; do
  python3 - "$file" "$PAGES_BASE_PATH" <<'PY'
import sys
from pathlib import Path
path = Path(sys.argv[1])
base = sys.argv[2]
text = path.read_text(encoding="utf-8")
old = '<base href="/" />'
new = f'<base href="{base}" />'
if old not in text:
    raise SystemExit(f"missing base tag in {path}")
path.write_text(text.replace(old, new, 1), encoding="utf-8")
PY
done

# Escape values for JS string literals
js_escape() {
  python3 -c 'import json,sys; print(json.dumps(sys.argv[1]))' "$1"
}

API_JS="$(js_escape "$API_BASE_URL")"
if [[ -n "$SHORTCUT_INSTALL_URL" ]]; then
  SHORTCUT_JS="$(js_escape "$SHORTCUT_INSTALL_URL")"
else
  SHORTCUT_JS="null"
fi

cat > "$OUT_DIR/assets/site-config.js" <<EOF
/* Generated by scripts/build-pages.sh — do not edit by hand on Pages. */
window.UNI_SHARE_SITE = {
  apiBaseUrl: ${API_JS},
  shortcutInstallUrl: ${SHORTCUT_JS},
};
EOF

echo "Built Pages site → $OUT_DIR"
echo "  base href:      $PAGES_BASE_PATH"
echo "  apiBaseUrl:     ${API_BASE_URL:-"(empty — same-origin only)"}"
echo "  shortcutInstallUrl: ${SHORTCUT_INSTALL_URL:-null}"
